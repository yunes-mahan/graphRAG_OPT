"""Global sensemaking questions (the use case GraphRAG summaries are designed for), following Edge et al. 2024.

30 corpus-level questions are generated by gpt-5.6-terra from a description of the corpus and 60 random titles
(no maintainer output is shown). Each store answers with ALL of its community summaries in context (global
search; the summaries fit into one prompt), vector RAG answers from retrieved papers:
  summaries: FRESH | hybrid tau=0.9 | hybrid never-refresh (stale) | recompute tau=0.9 | FRESH title-only
  vector   : 12 papers (same budget as the local QA) | budget-matched (as many papers as the FRESH summaries' chars)
Evaluation: gpt-5.6-terra compares each store's answer with the FRESH answer on comprehensiveness, diversity,
empowerment and directness; both presentation orders; win = 1, tie = 0.5, averaged over orders.
Writes qa_global.json.
"""

import concurrent.futures as cf
import hashlib
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).parent))
import config  # noqa: E402
import qa_plan as qp  # noqa: E402
import qa_run as qr  # noqa: E402

HERE = config.RESULTS
QA = HERE / "qa"
CRIT = ["comprehensiveness", "diversity", "empowerment", "directness"]
N_Q = 30


def questions(docs, cache):
    if cache.get("global"):
        return cache.get("global")["items"]
    rng = np.random.default_rng(3)
    titles = "\n".join(f"- {docs[int(i)][0]}" for i in rng.choice(len(docs), 60, replace=False))
    prompt = (f"A knowledge base contains {len(docs):,} computer-science research papers (2007-2020) on information "
              "retrieval, databases, social and information networks, and digital libraries. A random sample of "
              f"titles:\n{titles}\n\nWrite {N_Q} diverse GLOBAL questions that different users (e.g. a new PhD student, "
              "a research manager, an industry architect, a funding officer, a journalist) might ask about the WHOLE "
              "collection, which require an understanding of the corpus as a whole rather than of a few papers "
              "(e.g. 'What are the main research themes and how have they shifted over time?'). Do not mention "
              'specific papers. Return JSON {"questions": [str, ...]}.')
    text, usage = qr.call(qr.Q_MODEL, [{"role": "user", "content": prompt}], json_mode=True, max_tokens=4000)
    items = json.loads(text)["questions"][:N_Q]
    cache.put("global", dict(items=items, usage=usage))
    return items


def answer(q, blocks, store, cache):
    k = hashlib.sha1(("global|" + store + "|" + q).encode()).hexdigest()
    hit = cache.get(k)
    if hit:
        return hit
    prompt = ("Answer the question using ONLY the material below. Give a well-organised answer of at most 400 "
              "words.\n\n" f"Question: {q}\n\nMaterial:\n" + "\n\n".join(blocks))
    text, usage = qr.call(qr.ANS_MODEL, [{"role": "user", "content": prompt}], max_tokens=2500)
    out = dict(text=text, usage=usage)
    cache.put(k, out)
    return out


def compare(q, a, b, cache):
    k = hashlib.sha1(("cmp|" + q + "|" + a + "|" + b).encode()).hexdigest()
    hit = cache.get(k)
    if hit:
        return hit
    prompt = (f"Question: {q}\n\nAnswer 1:\n{a}\n\nAnswer 2:\n{b}\n\nCompare the two answers on four criteria: "
              "comprehensiveness (covers all aspects of the question), diversity (varied perspectives and insights), "
              "empowerment (helps the reader understand and make informed judgements), directness (addresses the "
              "question specifically and clearly). For each criterion pick 1, 2 or 0 for a tie. Return JSON "
              '{"comprehensiveness": 0|1|2, "diversity": 0|1|2, "empowerment": 0|1|2, "directness": 0|1|2}.')
    for attempt in range(3):
        text, usage = qr.call(qr.JUDGE_MODEL, [{"role": "user", "content": prompt}], json_mode=True, max_tokens=2000)
        try:
            out = dict(v={c: int(json.loads(text)[c]) for c in CRIT}, usage=usage)
            break
        except (json.JSONDecodeError, KeyError, ValueError, TypeError):
            out = None
    if out is None:
        raise RuntimeError("judge failed three times")
    cache.put(k, out)
    return out


def main():
    plan = json.loads((QA / "plan.json").read_text())
    node_t = np.load(QA / "node_t.npy")
    nodes = pd.read_csv(QA / "nodes.csv")
    texts = qp.load_texts(nodes.paper_id.values)
    docs = {int(i): texts[int(p)] for i, p in zip(nodes.idx, nodes.paper_id)}
    cs, cv = qr.Cache("summaries"), qr.Cache("variants")
    cq, ca, cj = qr.Cache("questions"), qr.Cache("answers_global"), qr.Cache("judge_global")
    items = questions(docs, cq)
    lab = plan["methods"]["recompute_leiden"]["labels"][-1]
    present = np.where(node_t >= 0)[0]
    comm = {}
    for v, c in zip(present, lab):
        comm.setdefault(int(c), []).append(int(v))
    fresh = [sorted(m) for m in comm.values() if len(m) >= qp.MIN_SIZE]
    store_sets = {"summaries|fresh": fresh,
                  "summaries|hybrid tau=0.9": plan["methods"]["hybrid"]["taus"]["0.9"]["final_store"],
                  "summaries|hybrid never": plan["methods"]["hybrid"]["taus"]["0.0"]["final_store"],
                  "summaries|recompute tau=0.9": plan["methods"]["recompute_leiden"]["taus"]["0.9"]["final_store"]}
    blocks = {n: [f"Report {i + 1}:\n{cs.get(qr.key_of(sorted(s)))['text']}" for i, s in enumerate(ss)]
              for n, ss in store_sets.items()}
    blocks["summaries|fresh titles-only"] = [f"Report {i + 1}:\n{cv.get('titles<=300|' + qr.key_of(s))['text']}"
                                             for i, s in enumerate(fresh)]
    E = np.load(QA / "emb_te3small.npy")
    E /= np.linalg.norm(E, axis=1, keepdims=True)
    gq = QA / "emb_global_questions.npy"
    if gq.exists():
        Qe = np.load(gq)
    else:
        r = qr.client.embeddings.create(model="text-embedding-3-small", input=items)
        Qe = np.asarray([d.embedding for d in r.data], dtype=np.float32)
        np.save(gq, Qe)
    Qe /= np.linalg.norm(Qe, axis=1, keepdims=True)
    budget = sum(len(b) for b in blocks["summaries|fresh"])
    paper = lambda v: f"- {docs[v][0]}: {docs[v][1][:600]}"  # noqa: E731
    n_match = int(budget / np.mean([len(paper(int(v))) for v in present[:2000]]))

    def store_blocks(name, qi):
        if name.startswith("summaries"):
            return blocks[name]
        k = 12 if name == "vector|12 papers" else n_match
        best = present[np.argsort(-(E[present] @ Qe[qi]))[:k]]
        return [paper(int(v)) for v in best]

    names = list(blocks) + ["vector|12 papers", f"vector|{n_match} papers (budget-matched)"]
    jobs = [(n, i) for n in names for i in range(len(items))]
    with cf.ThreadPoolExecutor(8) as ex:
        ans = dict(zip(jobs, ex.map(lambda j: answer(items[j[1]], store_blocks(j[0], j[1]), j[0], ca), jobs)))
    rows = []
    cmp_jobs = [(n, i, order) for n in names if n != "summaries|fresh" for i in range(len(items)) for order in (0, 1)]

    def do(j):
        n, i, order = j
        a, f = ans[(n, i)]["text"], ans[("summaries|fresh", i)]["text"]
        r = compare(items[i], *((a, f) if order == 0 else (f, a)), cj)["v"]
        mine = 1 if order == 0 else 2
        return dict(store=n, q=i, order=order, **{c: 1.0 if r[c] == mine else 0.5 if r[c] == 0 else 0.0
                                                   for c in CRIT})

    with cf.ThreadPoolExecutor(8) as ex:
        rows = list(ex.map(do, cmp_jobs))
    df = pd.DataFrame(rows).groupby(["store", "q"])[CRIT].mean().reset_index()
    out = []
    for n in names[1:]:
        d = df[df.store == n]
        rec = dict(store=n, input_tokens=float(np.mean([ans[(n, i)]["usage"]["inp"] for i in range(len(items))])))
        for c in CRIT:
            rec[c] = d[c].mean()
            rec[c + "_p"] = stats.wilcoxon(d[c] - 0.5).pvalue if (d[c] != 0.5).any() else 1.0
        out.append(rec)
    res = pd.DataFrame(out)
    print("win rate against FRESH summaries (0.5 = equal; p: Wilcoxon vs 0.5)")
    print(res.round(3).to_string(index=False))
    print(f"fresh summaries context tokens: {np.mean([ans[('summaries|fresh', i)]['usage']['inp'] for i in range(len(items))]):.0f}")
    (HERE / "qa_global.json").write_text(json.dumps(dict(summary=out, rows=rows, questions=items, n_match=n_match),
                                                    indent=1, default=float))


if __name__ == "__main__":
    main()
